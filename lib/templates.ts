import { makeId } from "@/lib/id";
import type { CanvasElement, DesignPage, TemplateRecord } from "@/lib/types";

function clonePages(pages: DesignPage[]): DesignPage[] {
  return pages.map((p) => ({
    ...p,
    id: makeId("pg"),
    elements: p.elements.map((e) => ({ ...e, id: makeId("el") }) as CanvasElement),
  }));
}

export function instantiateTemplate(tpl: TemplateRecord): DesignPage[] {
  return clonePages(tpl.pages);
}

